//! Emit `docs/css-spec.json` from the tables in `hikari_core::spec`.
//!
//! # Why an example and not a scraper
//!
//! The first attempt read `css.rs` and pulled property names out of the `match`
//! with a regular expression. It produced 89 properties, and among them
//! `filter` was *missing* -- because that arm is written
//! `"filter" | "backdrop-filter" =>`, which the pattern did not match -- while
//! `white`, `block` and `fixed` were *included*, because those are values of other
//! properties matched at the same indentation.
//!
//! A spec with those errors is worse than no spec, since it is a contract
//! somebody will write a stylesheet against. So the tables are declared in Rust
//! next to the parser, and this example serialises them. The extraction that can
//! go wrong is gone rather than tuned.
//!
//! Run: `cargo run -p hikari-rs --example css_spec`

use hikari_core::spec::{Property, REPORTED, SUPPORTED};

fn entry(p: &Property, supported: bool) -> serde_json::Value {
    serde_json::json!({
        "property": p.name,
        "supported": supported,
        "value": p.value,
        "note": p.note,
    })
}

fn main() {
    let supported: Vec<_> = SUPPORTED.iter().map(|p| entry(p, true)).collect();
    let reported: Vec<_> = REPORTED.iter().map(|p| entry(p, false)).collect();

    let doc = serde_json::json!({
        "$comment": concat!(
            "Generated by `cargo run -p hikari-rs --example css_spec` from ",
            "crates/hikari-core/src/spec.rs. Do not edit by hand.",
            "The table is checked against the parser by ",
            "`hikari_core::spec::conformance`, so it cannot drift without a test failing.",
        ),
        "spec": "hikari-css-subset",
        "version": env!("CARGO_PKG_VERSION"),
        "counts": {
            "supported": supported.len(),
            "reportedRefused": reported.len(),
        },
        "supported": supported,
        "reportedRefused": reported,
    });

    let path = std::path::Path::new("docs/css-spec.json");
    if let Some(dir) = path.parent() {
        let _ = std::fs::create_dir_all(dir);
    }
    let mut json = serde_json::to_string_pretty(&doc).expect("serialises");
    json.push('\n');
    std::fs::write(path, json).expect("writes docs/css-spec.json");
    println!(
        "wrote docs/css-spec.json — {} supported, {} recognised-and-refused",
        SUPPORTED.len(),
        REPORTED.len()
    );
}
